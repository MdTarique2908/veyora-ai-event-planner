/**
 * iCalendar (RFC 5545) generator utility for Veyora.
 * Exports events, preparation milestones, and day-of schedules to .ics format
 * compatible with Apple Calendar, Google Calendar, Microsoft Outlook, and mobile devices.
 */

import { EventPlan, TaskPhase } from '../types/event';

export interface CalendarExportOptions {
  includeMainEvent?: boolean;
  includeMilestones?: boolean;
  includeDayOfSchedule?: boolean;
  milestoneFilter?: 'all' | 'pending-only';
  alarmMinutesBefore?: number; // e.g. 1440 for 1 day before
}

/**
 * Escapes characters for iCalendar RFC 5545 text fields
 */
export function escapeIcsText(text: string): string {
  if (!text) return '';
  return text
    .replace(/\\/g, '\\\\')
    .replace(/;/g, '\\;')
    .replace(/,/g, '\\,')
    .replace(/\r?\n/g, '\\n');
}

/**
 * Pads number with leading zero
 */
function pad(num: number): string {
  return num < 10 ? `0${num}` : `${num}`;
}

/**
 * Formats a Date object to YYYYMMDD string for all-day events
 */
export function formatIcsDateOnly(date: Date): string {
  const year = date.getFullYear();
  const month = pad(date.getMonth() + 1);
  const day = pad(date.getDate());
  return `${year}${month}${day}`;
}

/**
 * Formats a Date object to UTC YYYYMMDDTHHMMSSZ for timestamped events
 */
export function formatIcsDateTimeUtc(date: Date): string {
  const year = date.getUTCFullYear();
  const month = pad(date.getUTCMonth() + 1);
  const day = pad(date.getUTCDate());
  const hours = pad(date.getUTCHours());
  const minutes = pad(date.getUTCMinutes());
  const seconds = pad(date.getUTCSeconds());
  return `${year}${month}${day}T${hours}${minutes}${seconds}Z`;
}

/**
 * Maps task phase to relative offset in days from the event date
 */
export function getPhaseOffsetDays(phase: TaskPhase): number {
  switch (phase) {
    case '8+ Weeks Before':
      return -56;
    case '4-6 Weeks Before':
      return -35;
    case '2-3 Weeks Before':
      return -18;
    case '1 Week Before':
      return -7;
    case 'Day Before':
      return -1;
    case 'Event Day':
      return 0;
    case 'Post Event':
      return 1;
    default:
      return -7;
  }
}

/**
 * Calculates milestone target date based on event date and phase or custom due date
 */
export function calculateMilestoneDate(
  eventDateStr: string,
  duePhase: TaskPhase,
  customDueDate?: string
): Date {
  if (customDueDate) {
    const parsed = new Date(customDueDate);
    if (!isNaN(parsed.getTime())) {
      return parsed;
    }
  }

  // Parse YYYY-MM-DD safely in local time
  const [y, m, d] = eventDateStr.split('-').map(Number);
  const baseDate = new Date(y, m - 1, d);
  const offset = getPhaseOffsetDays(duePhase);

  const calculated = new Date(baseDate);
  calculated.setDate(calculated.getDate() + offset);
  return calculated;
}

/**
 * Parses time strings like "10:00 AM", "14:30", "6:00 PM" into hours and minutes
 */
export function parseScheduleTimeString(timeStr: string): { hours: number; minutes: number } {
  if (!timeStr) return { hours: 10, minutes: 0 };

  const clean = timeStr.trim().toLowerCase();
  const isPm = clean.includes('pm');
  const isAm = clean.includes('am');

  const numbersOnly = clean.replace(/[^\d:]/g, '');
  const parts = numbersOnly.split(':').map(Number);

  let hours = parts[0] || 10;
  const minutes = parts[1] || 0;

  if (isPm && hours < 12) {
    hours += 12;
  } else if (isAm && hours === 12) {
    hours = 0;
  }

  return { hours: Math.min(Math.max(hours, 0), 23), minutes: Math.min(Math.max(minutes, 0), 59) };
}

/**
 * Generates RFC 5545 compliant .ics content for an EventPlan
 */
export function generateEventPlanIcs(
  plan: EventPlan,
  options: CalendarExportOptions = {}
): string {
  const {
    includeMainEvent = true,
    includeMilestones = true,
    includeDayOfSchedule = true,
    milestoneFilter = 'all',
    alarmMinutesBefore = 1440, // 24 hours
  } = options;

  const now = new Date();
  const dtstamp = formatIcsDateTimeUtc(now);
  const calendarId = `veyora-${plan.id || Date.now()}`;

  // Parse main event date
  const [year, month, day] = plan.input.eventDate.split('-').map(Number);
  const eventDateObj = new Date(year, month - 1, day);
  const nextDayObj = new Date(year, month - 1, day + 1);

  const lines: string[] = [
    'BEGIN:VCALENDAR',
    'VERSION:2.0',
    'PRODID:-//Veyora//Every Occasion Extraordinary//EN',
    'CALSCALE:GREGORIAN',
    'METHOD:PUBLISH',
    `X-WR-CALNAME:${escapeIcsText(plan.concept.title || plan.input.title || 'Veyora Celebration')}`,
    'X-WR-CALDESC:Celebration plan and milestones generated by Veyora',
  ];

  // 1. Main Event VEVENT
  if (includeMainEvent) {
    const mainUid = `${calendarId}-main@veyora.ai`;
    const dtstart = formatIcsDateOnly(eventDateObj);
    const dtend = formatIcsDateOnly(nextDayObj);

    const descriptionParts = [
      `🎉 ${plan.concept.title}`,
      `"${plan.concept.tagline}"`,
      '',
      plan.concept.description,
      '',
      `Type: ${plan.input.eventType.toUpperCase()}`,
      `Guests: ${plan.input.guestCount}`,
      `Budget: ${plan.budgetPlan.currency} ${plan.budgetPlan.totalBudget.toLocaleString()}`,
      `Venue Preference: ${plan.input.venuePreference}`,
      `Theme Style: ${plan.input.themeStyle}`,
    ];

    if (plan.practicalTips && plan.practicalTips.length > 0) {
      descriptionParts.push('', '--- Key Tips ---');
      plan.practicalTips.slice(0, 4).forEach((tip, idx) => {
        descriptionParts.push(`${idx + 1}. ${typeof tip === 'string' ? tip : JSON.stringify(tip)}`);
      });
    }

    lines.push(
      'BEGIN:VEVENT',
      `UID:${mainUid}`,
      `DTSTAMP:${dtstamp}`,
      `DTSTART;VALUE=DATE:${dtstart}`,
      `DTEND;VALUE=DATE:${dtend}`,
      `SUMMARY:🎉 ${escapeIcsText(plan.concept.title || plan.input.title)}`,
      `DESCRIPTION:${escapeIcsText(descriptionParts.join('\n'))}`,
      `LOCATION:${escapeIcsText(`${plan.input.city} (${plan.input.venuePreference})`)}`,
      'STATUS:CONFIRMED',
      'TRANSP:OPAQUE',
      'CLASS:PUBLIC',
      'PRIORITY:1'
    );

    // Optional 24h reminder alarm
    if (alarmMinutesBefore > 0) {
      lines.push(
        'BEGIN:VALARM',
        'ACTION:DISPLAY',
        `DESCRIPTION:Reminder: ${escapeIcsText(plan.concept.title)} is tomorrow!`,
        `TRIGGER:-PT${alarmMinutesBefore}M`,
        'END:VALARM'
      );
    }

    lines.push('END:VEVENT');
  }

  // 2. Timeline Preparation Milestones
  if (includeMilestones && plan.timeline && plan.timeline.length > 0) {
    const filteredTasks = plan.timeline.filter((task) => {
      if (milestoneFilter === 'pending-only') {
        return !task.isCompleted;
      }
      return true;
    });

    filteredTasks.forEach((task, index) => {
      const taskDate = calculateMilestoneDate(
        plan.input.eventDate,
        task.duePhase,
        task.dueDate
      );
      const nextDay = new Date(taskDate);
      nextDay.setDate(nextDay.getDate() + 1);

      const taskUid = `${calendarId}-task-${task.id || index}@veyora.ai`;
      const dtstart = formatIcsDateOnly(taskDate);
      const dtend = formatIcsDateOnly(nextDay);

      const taskDesc = [
        `Milestone: ${task.title}`,
        `Phase: ${task.duePhase}`,
        `Category: ${task.category}`,
        `Priority: ${task.priority.toUpperCase()}`,
        `Status: ${task.isCompleted ? 'COMPLETED' : 'PENDING'}`,
        '',
        task.description,
        '',
        `Event: ${plan.concept.title} (${plan.input.eventDate})`,
      ].join('\n');

      let icsPriority = '5';
      if (task.priority === 'high') icsPriority = '1';
      if (task.priority === 'low') icsPriority = '9';

      lines.push(
        'BEGIN:VEVENT',
        `UID:${taskUid}`,
        `DTSTAMP:${dtstamp}`,
        `DTSTART;VALUE=DATE:${dtstart}`,
        `DTEND;VALUE=DATE:${dtend}`,
        `SUMMARY:📋 [Milestone] ${escapeIcsText(task.title)}`,
        `DESCRIPTION:${escapeIcsText(taskDesc)}`,
        `CATEGORIES:${escapeIcsText(task.category || 'Planning')}`,
        `STATUS:${task.isCompleted ? 'COMPLETED' : 'CONFIRMED'}`,
        `PRIORITY:${icsPriority}`,
        'TRANSP:TRANSPARENT'
      );

      // Alarm for high priority milestones (morning of due date)
      if (task.priority === 'high') {
        lines.push(
          'BEGIN:VALARM',
          'ACTION:DISPLAY',
          `DESCRIPTION:Milestone due today: ${escapeIcsText(task.title)}`,
          'TRIGGER:-PT0M',
          'END:VALARM'
        );
      }

      lines.push('END:VEVENT');
    });
  }

  // 3. Day-of Run of Show / Schedule Items
  if (includeDayOfSchedule && plan.dayOfSchedule && plan.dayOfSchedule.length > 0) {
    plan.dayOfSchedule.forEach((item, index) => {
      const { hours, minutes } = parseScheduleTimeString(item.time);
      const startObj = new Date(year, month - 1, day, hours, minutes, 0);

      // Default duration: 45 minutes or 1 hour
      const endObj = new Date(startObj.getTime() + 45 * 60 * 1000);

      const itemUid = `${calendarId}-schedule-${index}@veyora.ai`;
      const dtstart = formatIcsDateTimeUtc(startObj);
      const dtend = formatIcsDateTimeUtc(endObj);

      const itemDesc = [
        `Activity: ${item.activity}`,
        `Scheduled Time: ${item.time}`,
        `Lead/Owner: ${item.owner || 'Event Coordinator'}`,
        '',
        item.details || 'Day-of celebration schedule item.',
        '',
        `Event: ${plan.concept.title}`,
      ].join('\n');

      lines.push(
        'BEGIN:VEVENT',
        `UID:${itemUid}`,
        `DTSTAMP:${dtstamp}`,
        `DTSTART:${dtstart}`,
        `DTEND:${dtend}`,
        `SUMMARY:⏱️ ${item.time} - ${escapeIcsText(item.activity)}`,
        `DESCRIPTION:${escapeIcsText(itemDesc)}`,
        `LOCATION:${escapeIcsText(plan.input.city)}`,
        'STATUS:CONFIRMED',
        'TRANSP:OPAQUE'
      );

      lines.push('END:VEVENT');
    });
  }

  lines.push('END:VCALENDAR');

  // RFC 5545 requires CRLF line endings
  return lines.join('\r\n');
}

/**
 * Triggers browser download of generated .ics content
 */
export function downloadIcsFile(filename: string, icsContent: string): void {
  const safeFilename = filename.endsWith('.ics') ? filename : `${filename}.ics`;
  const blob = new Blob([icsContent], { type: 'text/calendar;charset=utf-8' });
  const url = window.URL.createObjectURL(blob);
  const link = document.createElement('a');
  link.href = url;
  link.setAttribute('download', safeFilename);
  document.body.appendChild(link);
  link.click();
  document.body.removeChild(link);
  window.URL.revokeObjectURL(url);
}

/**
 * Creates a direct Google Calendar Web template URL for 1-click addition of the main event
 */
export function createGoogleCalendarUrl(plan: EventPlan): string {
  const [year, month, day] = plan.input.eventDate.split('-').map(Number);
  const startStr = `${year}${pad(month)}${pad(day)}`;
  const endObj = new Date(year, month - 1, day + 1);
  const endStr = `${endObj.getFullYear()}${pad(endObj.getMonth() + 1)}${pad(endObj.getDate())}`;

  const title = `🎉 ${plan.concept.title || plan.input.title}`;
  const details = `${plan.concept.tagline ? `"${plan.concept.tagline}"\n\n` : ''}${plan.concept.description}\n\nGuests: ${plan.input.guestCount}\nBudget: ${plan.budgetPlan.currency} ${plan.budgetPlan.totalBudget.toLocaleString()}\nPlanned with Veyora — Every occasion, extraordinary.`;
  const location = `${plan.input.city} (${plan.input.venuePreference})`;

  const params = new URLSearchParams({
    action: 'TEMPLATE',
    text: title,
    dates: `${startStr}/${endStr}`,
    details: details,
    location: location,
  });

  return `https://calendar.google.com/calendar/render?${params.toString()}`;
}
